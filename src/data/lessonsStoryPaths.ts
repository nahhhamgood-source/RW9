import type { DailyCutLesson, MindsetPathId } from '../types';

type StoryLessonSeed = [
  title: string,
  idea: string,
  ideaSpoilerFree: string,
  matureSafeSummary: string,
  moveToday: string,
  protocolId: string,
  realityCheck: string,
  focusTag?: 'fight_camp' | 'study' | 'sleep' | 'general',
  arabicHint?: string,
];

function buildStoryLessons(
  pathId: MindsetPathId,
  watchMoreTitle: string,
  watchSearchQuery: string,
  seeds: StoryLessonSeed[]
): DailyCutLesson[] {
  return seeds.map(
    (
      [
        title,
        idea,
        ideaSpoilerFree,
        matureSafeSummary,
        moveToday,
        protocolId,
        realityCheck,
        focusTag,
        arabicHint,
      ],
      idx
    ) => ({
      id: `${pathId}-cut-${idx + 1}`,
      pathId,
      dayIndex: idx + 1,
      title,
      idea,
      ideaSpoilerFree,
      matureSafeSummary,
      arabicHint,
      moveToday,
      protocolId,
      realityCheck,
      watchMoreTitle,
      watchSearchQuery,
      focusTag: focusTag ?? 'general',
    })
  );
}

function expandTo30(
  core: StoryLessonSeed[],
  rotations: Array<{ suffix: string; move: string; protocolId: string; reality: string; focus?: 'fight_camp' | 'study' | 'sleep' | 'general' }>
): StoryLessonSeed[] {
  const out: StoryLessonSeed[] = [...core];
  let i = 0;
  while (out.length < 30) {
    const base = core[i % core.length];
    const rot = rotations[i % rotations.length];
    out.push([
      `${base[0]} — ${rot.suffix}`,
      base[1],
      base[2],
      base[3],
      rot.move,
      rot.protocolId,
      `${base[6]} ${rot.reality}`.trim(),
      rot.focus ?? base[7] ?? 'general',
    ]);
    i++;
  }
  return out.slice(0, 30);
}

