import type { DailyCutLesson, MindsetPathId } from '../types';

type LessonSeed = [
  title: string,
  idea: string,
  moveToday: string,
  protocolId: string,
  realityCheck: string,
  focusTag?: 'fight_camp' | 'study' | 'sleep' | 'general',
  arabicHint?: string,
];

function buildRealLessons(
  pathId: MindsetPathId,
  seeds: LessonSeed[],
  guardrailSuffix: string
): DailyCutLesson[] {
  return seeds.map(([title, idea, moveToday, protocolId, realityCheck, focusTag, arabicHint], idx) => ({
    id: `${pathId}-cut-${idx + 1}`,
    pathId,
    dayIndex: idx + 1,
    title,
    idea,
    ideaSpoilerFree: idea,
    matureSafeSummary: idea,
    arabicHint,
    moveToday,
    protocolId,
    realityCheck: `${realityCheck} ${guardrailSuffix}`.trim(),
    focusTag: focusTag ?? 'general',
  }));
}

