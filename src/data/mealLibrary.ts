export function evaluateMealFitForToday(
  calories: number,
  caloriesLeft: number
): 'Fits today' | 'Split or swap lighter' | 'Better on a training day' {
  if (calories <= Math.max(0, caloriesLeft) + 60) return 'Fits today';
  if (calories <= Math.max(0, caloriesLeft) + 250) return 'Split or swap lighter';
  return 'Better on a training day';
}

